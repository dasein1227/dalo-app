function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, JSON.stringify(value, null, 2) + '\n', 'utf8');
}

function ensureObject(parent, key) {
  if (!parent[key] || typeof parent[key] !== 'object' || Array.isArray(parent[key])) {
    parent[key] = {};
  }
  return parent[key];
}

function main() {
  const root = process.cwd();
  const baseDir = path.join(root, 'src', 'locales');
  const missing = [];
  const updated = [];

  for (const locale of LOCALES) {
    const filePath = path.join(baseDir, locale, 'chat.json');
    if (!fs.existsSync(filePath)) {
      missing.push(filePath);
      continue;
    }

    const chat = readJson(filePath);
    const panel = ensureObject(chat, 'translationPanel');
    const language = ensureObject(panel, 'language');
    const labels = LANGUAGE_LABELS[locale] || LANGUAGE_LABELS.en;

    for (const [code, label] of Object.entries(labels)) {
      language[code] = label;
    }

    writeJson(filePath, chat);
    updated.push(path.relative(root, filePath));
  }

  console.log(`[translationPanel.language] updated ${updated.length} files`);
  for (const file of updated) console.log(`  - ${file}`);

  if (missing.length) {
    console.warn(`[translationPanel.language] missing ${missing.length} files`);
    for (const file of missing) console.warn(`  - ${file}`);
  }
}

main();
