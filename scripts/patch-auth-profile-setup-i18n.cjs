function mergeDeep(target, patch) {
  for (const [key, value] of Object.entries(patch)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      target[key] = mergeDeep(target[key] && typeof target[key] === 'object' && !Array.isArray(target[key]) ? target[key] : {}, value);
    } else {
      target[key] = value;
    }
  }
  return target;
}

const root = process.cwd();

for (const [lang, patch] of Object.entries(patches)) {
  const filePath = path.join(root, 'src', 'locales', lang, 'auth.json');
  if (!fs.existsSync(filePath)) {
    console.log(`skip ${lang}`);
    continue;
  }

  const current = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  current.profileSetup = mergeDeep(current.profileSetup || {}, patch);
  fs.writeFileSync(filePath, `${JSON.stringify(current, null, 2)}\n`, 'utf8');
  console.log(`patched ${lang}`);
}
