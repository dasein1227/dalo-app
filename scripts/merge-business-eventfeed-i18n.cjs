function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function deepMerge(target, source) {
  const out = isPlainObject(target) ? { ...target } : {};
  for (const [key, value] of Object.entries(source)) {
    if (isPlainObject(value)) {
      out[key] = deepMerge(out[key], value);
    } else {
      out[key] = value;
    }
  }
  return out;
}

function readJson(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  return JSON.parse(raw);
}

function writeJson(filePath, data) {
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function ensureBackup(filePath) {
  const backupPath = `${filePath}${BACKUP_SUFFIX}`;
  if (!fs.existsSync(backupPath)) {
    fs.copyFileSync(filePath, backupPath);
    return backupPath;
  }
  return null;
}

function main() {
  const root = process.cwd();
  const changed = [];
  const skipped = [];
  const backups = [];

  for (const locale of LOCALES) {
    const filePath = path.join(root, 'src', 'locales', locale, 'business.json');
    if (!fs.existsSync(filePath)) {
      skipped.push(`${locale}: missing ${path.relative(root, filePath)}`);
      continue;
    }

    const additions = eventFeedByLocale[locale];
    if (!additions) {
      skipped.push(`${locale}: no translation payload`);
      continue;
    }

    const before = fs.readFileSync(filePath, 'utf8');
    let json;
    try {
      json = JSON.parse(before);
    } catch (err) {
      throw new Error(`[${locale}] invalid JSON: ${filePath}\n${err.message}`);
    }

    const next = {
      ...json,
      eventFeed: deepMerge(json.eventFeed, additions),
    };

    const after = `${JSON.stringify(next, null, 2)}\n`;
    if (after !== before) {
      const backup = ensureBackup(filePath);
      if (backup) backups.push(path.relative(root, backup));
      fs.writeFileSync(filePath, after, 'utf8');
      // Verify immediately after writing.
      readJson(filePath);
      changed.push(path.relative(root, filePath));
    }
  }

  console.log('[business eventFeed i18n] changed files:', changed.length ? changed.join(', ') : 'none');
  console.log('[business eventFeed i18n] backups:', backups.length ? backups.join(', ') : `${BACKUP_SUFFIX} already existed or no changes`);
  if (skipped.length) {
    console.log('[business eventFeed i18n] skipped:', skipped.join(' | '));
  }
}

main();
